"""Verified local source and procedural granular texture export.

The optional nature source is entirely generated by Sonumio's original
mathematical renderer. A supplied WAV is accepted only through a bounded,
fully verified canonical PCM snapshot. Export is single-file, atomic,
and never accesses an external audio service.
"""
from __future__ import annotations

from dataclasses import dataclass, asdict
import hashlib
import os
from pathlib import Path
import numpy as np

from .contracts import AudioSpec, AudioLayout, make_buffer
from .errors import AudioContractError, AudioFormatError, AudioIntegrityError, AudioLimitError
from .hashing import canonical_json_bytes, digest_audio, strict_sha256
from .granular import GranularSettings, GranularReport, synthesize_grains
from .wave_snapshot import read_verified_pcm
from .waveio import encode_wav_bytes
from .dither import QuantizationSettings

MAX_EXPORT_PCM_BYTES = 24*1024*1024


@dataclass(frozen=True, slots=True)
class ProceduralGrainSource:
    kind: str = "rain"
    frames: int = 12000
    intensity: float = .5
    texture: float = .5
    motion: float = .5
    seed: int = 0

    def __post_init__(self):
        from ..nature_synthesis import NatureVoice, SAMPLE_RATE, MAX_FRAMES
        try:
            self.voice()
        except ValueError as exc:
            raise AudioContractError(str(exc)) from exc
        if type(self.frames) is not int or not SAMPLE_RATE//10 <= self.frames <= MAX_FRAMES:
            raise AudioContractError("Invalid procedural source duration")

    def voice(self):
        from ..nature_synthesis import NatureVoice
        return NatureVoice(self.kind,self.intensity,self.texture,self.motion,self.seed)

    def as_dict(self):
        return asdict(self)


@dataclass(frozen=True, slots=True)
class GranularExportOptions:
    settings: GranularSettings
    output_bits: int | None = None
    dither_seed: int | None = None
    packet_frames: int = 8192

    def __post_init__(self):
        if not isinstance(self.settings,GranularSettings):
            raise AudioContractError("Expected GranularSettings")
        if self.output_bits is not None:
            QuantizationSettings(bits=self.output_bits)
        if self.dither_seed is not None:
            QuantizationSettings(dither=True,seed=self.dither_seed)
        if type(self.packet_frames) is not int or not 1 <= self.packet_frames <= 65536:
            raise AudioContractError("Invalid source reader packet length")


@dataclass(frozen=True, slots=True)
class GranularExport:
    source: dict
    output_sha256: str
    output_pcm_sha256: str
    output_bytes: int
    output_bits: int
    dither_seed: int | None
    render: GranularReport
    protocol: str = "sonumio-granular-wav-export-v1"

    def as_dict(self):
        return {
            "protocol": self.protocol,
            "source": self.source,
            "output_sha256": self.output_sha256,
            "pre_encoding_pcm_sha256": self.output_pcm_sha256,
            "output_bytes": self.output_bytes,
            "output_bits": self.output_bits,
            "dither_seed": self.dither_seed,
            "render": self.render.as_dict(),
            "model_inference": False,
        }


def _distinct_paths(source,destination):
    if source.resolve()==destination.resolve():
        raise AudioFormatError("Granular source and destination must differ")
    if destination.exists():
        try:
            if os.path.samefile(source,destination):
                raise AudioFormatError("Granular paths share a file identity")
        except FileNotFoundError:
            pass


def _validate_export(destination,options,overwrite,create_parent,expected_output_sha256):
    if not isinstance(options,GranularExportOptions):
        raise AudioContractError("Expected GranularExportOptions")
    if type(overwrite) is not bool or type(create_parent) is not bool:
        raise AudioContractError("Invalid granular export flags")
    if expected_output_sha256 is not None:
        strict_sha256(expected_output_sha256)
    target=Path(destination)
    if target.suffix.lower()!=".wav":
        raise AudioFormatError("Granular destination must end in .wav")
    return target


def _render_export(audio,source_metadata,target,bits,options,*,overwrite,
                   create_parent,expected_output_sha256,source_path=None):
    from ..atomic_cli_wav import publish_generated_wav
    channels=2 if audio.channels==1 and options.settings.stereo_spread else audio.channels
    spec=AudioSpec(audio.sample_rate,AudioLayout.for_channels(channels),
                   options.settings.output_frames)
    if spec.byte_count>MAX_EXPORT_PCM_BYTES:
        raise AudioLimitError("Granular WAV output exceeds offline PCM budget")
    result=synthesize_grains(audio,options.settings)
    if np.max(np.abs(result.audio.samples))>1:
        raise AudioContractError("Granular PCM exceeds normalized range; specify a peak ceiling")
    wav=encode_wav_bytes(result.audio,settings=QuantizationSettings(
        bits=bits,dither=options.dither_seed is not None,seed=options.dither_seed))
    if source_path is not None:
        _distinct_paths(source_path,target)
    published=publish_generated_wav(target,wav,overwrite=overwrite,
        create_parent=create_parent,expected_sha256=expected_output_sha256)
    return GranularExport(source_metadata,published.wav_sha256,digest_audio(result.audio),
        published.bytes_written,bits,options.dither_seed,result.report)


def export_granular_wav(source,destination,*,options,expected_sha256=None,
                       expected_output_sha256=None,overwrite=False,create_parent=False):
    target=_validate_export(destination,options,overwrite,create_parent,expected_output_sha256)
    source=Path(source)
    _distinct_paths(source,target)
    snapshot=read_verified_pcm(source,expected_sha256=expected_sha256,
                               packet_frames=options.packet_frames)
    metadata={**snapshot.as_dict(),"kind":"verified_local_pcm",
              "source_pcm_sha256":digest_audio(snapshot.audio)}
    bits=snapshot.info.bits_per_sample if options.output_bits is None else options.output_bits
    return _render_export(snapshot.audio,metadata,target,bits,options,
        overwrite=overwrite,create_parent=create_parent,
        expected_output_sha256=expected_output_sha256,source_path=source)


def export_procedural_grains(source,destination,*,options,
                             expected_source_pcm_sha256=None,expected_output_sha256=None,
                             overwrite=False,create_parent=False):
    from ..nature_synthesis import render_voice,SAMPLE_RATE
    from ..errors import GenerationError
    target=_validate_export(destination,options,overwrite,create_parent,expected_output_sha256)
    if not isinstance(source,ProceduralGrainSource):
        raise AudioContractError("Expected ProceduralGrainSource")
    if expected_source_pcm_sha256 is not None:
        strict_sha256(expected_source_pcm_sha256)
    try:
        audio=make_buffer(render_voice(source.voice(),source.frames),SAMPLE_RATE,
                          source_note="original procedural nature source")
    except GenerationError as exc:
        raise AudioContractError(str(exc)) from exc
    digest=digest_audio(audio)
    if expected_source_pcm_sha256 is not None and digest!=expected_source_pcm_sha256:
        raise AudioIntegrityError("Procedural grain source PCM digest mismatch")
    metadata={
        "kind":"original_procedural_nature",
        "settings":source.as_dict(),
        "settings_sha256":hashlib.sha256(canonical_json_bytes(source.as_dict())).hexdigest(),
        "source_pcm_sha256":digest,
        "source_frames":audio.frames,
        "sample_rate":audio.sample_rate,
        "source_channels":audio.channels,
    }
    return _render_export(audio,metadata,target,
        16 if options.output_bits is None else options.output_bits,options,
        overwrite=overwrite,create_parent=create_parent,
        expected_output_sha256=expected_output_sha256)
