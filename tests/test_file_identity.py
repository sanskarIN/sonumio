"""Portable path/descriptor identity checks and Windows precision fallbacks."""
from __future__ import annotations

import os
from pathlib import Path
from types import SimpleNamespace

import pytest

from sonumio._file_identity import (
    _windows_path_descriptor_matches, same_path_descriptor,
    same_path_identity, same_snapshot,
)


def snapshot(*, dev=3, inode=7, size=4096,
             mtime_ns=1_234_567_800_700_000_000,
             ctime_ns=1_234_567_700_000_000_000):
    return SimpleNamespace(
        st_dev=dev, st_ino=inode, st_size=size,
        st_mtime_ns=mtime_ns, st_ctime_ns=ctime_ns,
        st_mtime=mtime_ns / 1_000_000_000,
        st_ctime=ctime_ns / 1_000_000_000,
    )


def test_same_api_file_snapshot_detects_identity_and_metadata_changes():
    original = snapshot()
    assert same_snapshot(original, snapshot())
    assert same_path_identity(original, snapshot())
    for changed in (
        snapshot(dev=99), snapshot(inode=8), snapshot(size=4097),
        snapshot(mtime_ns=original.st_mtime_ns + 1),
        snapshot(ctime_ns=original.st_ctime_ns + 1),
    ):
        assert not same_snapshot(original, changed)


def test_windows_descriptor_precision_differences_do_not_reject_stable_file():
    original = snapshot(inode=997, dev=13)
    # Windows path stat supplies native file IDs/timestamps, while fstat
    # can have an absent CRT inode and second-level timestamp precision.
    coarse = snapshot(
        dev=0, inode=0, size=original.st_size,
        mtime_ns=original.st_mtime_ns - 500_000_000,
        ctime_ns=original.st_ctime_ns - 500_000_000,
    )
    assert not same_snapshot(original, coarse)
    assert _windows_path_descriptor_matches(original, coarse)
    assert not _windows_path_descriptor_matches(
        original, snapshot(size=original.st_size + 1),
    )
    assert not _windows_path_descriptor_matches(
        original, snapshot(mtime_ns=original.st_mtime_ns + 2_000_000_000),
    )


def test_platform_specific_path_descriptor_selection():
    orig = snapshot()
    coarse = snapshot(dev=0, inode=0, size=orig.st_size,
                      mtime_ns=orig.st_mtime_ns - 500_000_000)
    if os.name == "nt":
        assert same_path_descriptor(orig, coarse)
    else:
        assert not same_path_descriptor(orig, coarse)
        assert same_path_descriptor(orig, snapshot())


def test_path_identity_falls_back_to_times_when_platform_returns_zero_inode():
    base = snapshot(dev=0, inode=0)
    assert same_path_identity(base, snapshot(dev=0, inode=0))
    assert not same_path_identity(
        base, snapshot(dev=0, inode=0, mtime_ns=base.st_mtime_ns + 1),
    )


def test_actual_file_path_snapshot_detects_metadata_change(tmp_path):
    path = Path(tmp_path) / "metadata.wav"
    path.write_bytes(b"some locally generated bytes")
    previous = path.lstat()
    assert same_snapshot(previous, path.lstat())
    os.utime(
        path, ns=(previous.st_atime_ns, previous.st_mtime_ns + 2_000_000_000),
    )
    assert not same_snapshot(previous, path.lstat())


@pytest.mark.skipif(os.name != "nt", reason="Windows native/CRT stat check")
def test_windows_normal_local_file_can_be_opened_with_descriptor(tmp_path):
    path = tmp_path / "ordinary.wav"
    path.write_bytes(b"local Windows snapshot")
    before = path.lstat()
    with path.open("rb") as stream:
        fd_snapshot = os.fstat(stream.fileno())
        assert same_path_descriptor(before, fd_snapshot)
        assert stream.read() == b"local Windows snapshot"
    assert same_snapshot(before, path.lstat())
